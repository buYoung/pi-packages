#!/usr/bin/env node
// Source-only: writes src/core/protocol/schema.generated.ts from the proto/ tree, keeping only the types reached by the RPC
// methods and message codecs that src/ names. Run it after changing proto/ or adding an RPC. `--check` writes nothing and
// exits 1 when the file is out of date.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { isAbsolute, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const APP_ROOT = fileURLToPath(new URL("..", import.meta.url));
const PROTO_ROOT = join(APP_ROOT, "proto");
const SOURCE_ROOT = join(APP_ROOT, "src");
const SCHEMA_PATH = join(SOURCE_ROOT, "core/protocol/schema.generated.ts");
const protobuf = createRequire(import.meta.url)("protobufjs");

/** A full RPC path such as `exa.api_server_pb.ApiServerService/GetChatMessage`, and a type a message codec names. */
const METHOD_LITERAL = /"((?:[a-z_][a-z0-9_]*\.)+[A-Z]\w*\/[A-Z]\w*)"/g;
const CODEC_LITERAL = /messageCodec\("((?:[a-z_][a-z0-9_]*\.)+[A-Z]\w*)"\)/g;

function filesUnder(directory, extension, out = []) {
  for (const entry of readdirSync(directory)) {
    const path = join(directory, entry);
    if (statSync(path).isDirectory()) filesUnder(path, extension, out);
    else if (entry.endsWith(extension)) out.push(path);
  }
  return out.sort();
}

/** Parses the tree the way the runtime did before this file existed: every source, keepCase, imports resolved in the tree. */
function fullRoot() {
  const root = new protobuf.Root();
  root.resolvePath = (_origin, target) => isAbsolute(target) ? target : join(PROTO_ROOT, target);
  root.loadSync(filesUnder(PROTO_ROOT, ".proto"), { keepCase: true });
  root.resolveAll();
  return root;
}

function usedNames() {
  const methods = new Set(), types = new Set();
  for (const file of filesUnder(SOURCE_ROOT, ".ts")) {
    if (file === SCHEMA_PATH) continue;
    const text = readFileSync(file, "utf8");
    for (const [, name] of text.matchAll(METHOD_LITERAL)) methods.add(name);
    for (const [, name] of text.matchAll(CODEC_LITERAL)) types.add(name);
  }
  return { methods: [...methods].sort(), types: [...types].sort() };
}

/** The used services and methods, and every type their messages reach, including the types that enclose a nested one. */
function reachable(root, { methods, types }) {
  const kept = new Set(), queue = [], services = new Map();
  const keep = (type) => {
    if (type && !kept.has(type.fullName)) { kept.add(type.fullName); queue.push(type); }
  };
  for (const method of methods) {
    const split = method.lastIndexOf("/"), serviceName = method.slice(0, split), methodName = method.slice(split + 1);
    const definition = root.lookupService(serviceName).methods[methodName];
    if (!definition) throw new Error(`Not a method of ${serviceName} in proto/: ${methodName}`);
    keep(definition.resolvedRequestType);
    keep(definition.resolvedResponseType);
    services.set(serviceName, [...(services.get(serviceName) ?? []), methodName]);
  }
  for (const name of types) keep(root.lookupType(name));
  while (queue.length > 0) {
    const type = queue.pop();
    if (type.parent instanceof protobuf.Type) keep(type.parent);
    if (type instanceof protobuf.Type) for (const field of type.fieldsArray) keep(field.resolvedType);
  }
  return { kept, services };
}

/** The root's JSON with only those services, methods and types, in declaration order, so names resolve as in the full tree. */
function prune(json, prefix, { kept, services }) {
  if (!json.nested) return json;
  const nested = {};
  for (const [name, child] of Object.entries(json.nested)) {
    const fullName = prefix ? `${prefix}.${name}` : name;
    if (child.methods) {
      const used = services.get(fullName);
      if (used) nested[name] = { ...child, methods: Object.fromEntries(Object.entries(child.methods).filter(([method]) => used.includes(method))) };
      continue;
    }
    const isType = Boolean(child.fields || child.values);
    if (isType && !kept.has(`.${fullName}`)) continue;
    const pruned = prune(child, fullName, { kept, services });
    if (isType || Object.keys(pruned.nested ?? {}).length > 0) nested[name] = pruned;
  }
  return { ...json, nested };
}

function schemaSource() {
  const root = fullRoot(), used = usedNames(), selection = reachable(root, used);
  const schema = prune(root.toJSON({ keepComments: false }), "", selection);
  const methods = used.methods.map((name) => ` *   ${name}`).join("\n");
  return `// Generated by scripts/generate-schema.mjs from proto/. Do not edit; run \`pnpm run generate:schema\` instead.

/**
 * The ${selection.kept.size} types these methods and message codecs reach:
${methods}
 */
export const SCHEMA = ${JSON.stringify(schema, null, 2)};
`;
}

const source = schemaSource();
const target = relative(APP_ROOT, SCHEMA_PATH).split(sep).join("/");
if (process.argv.includes("--check")) {
  const current = (() => { try { return readFileSync(SCHEMA_PATH, "utf8"); } catch { return ""; } })();
  if (current !== source) {
    console.error(`${target} is out of date. Run \`pnpm run generate:schema\`.`);
    process.exit(1);
  }
  console.log(`${target} is up to date.`);
} else {
  writeFileSync(SCHEMA_PATH, source);
  console.log(`Wrote ${target}.`);
}
